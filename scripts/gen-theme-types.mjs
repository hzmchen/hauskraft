#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Generate TypeScript types from the theme contract (M0S-E13-01).
//
//   node scripts/gen-theme-types.mjs           write packages/ui/src/theme/contract.gen.ts
//   node scripts/gen-theme-types.mjs --check   exit 1 if the file is stale
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const theme = join(repo, "packages", "schemas", "theme");
const out = join(repo, "packages", "ui", "src", "theme", "contract.gen.ts");
const read = (name) => JSON.parse(readFileSync(join(theme, name), "utf8"));

const icons = read("icon-names-v1.json").icons;
const tokens = Object.keys(read("tokens-v1.json").tokens);
const layout = Object.fromEntries(Object.entries(read("layout-options-v1.json")).filter(([k]) => !k.startsWith("$")));

const pascal = (key) =>
  key
    .split(/[._]/)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
const constName = (key) => key.replace(/[.]/g, "_").toUpperCase();
const list = (values) => `[\n${values.map((v) => `  ${JSON.stringify(v)},`).join("\n")}\n] as const`;

let text = `// SPDX-License-Identifier: MIT
// GENERATED by scripts/gen-theme-types.mjs from packages/schemas/theme. Do not edit; run \`just gen\`.

/** Core semantic icon names, set v1 (spec §10.2.6). */
export const ICON_NAMES = ${list(icons)};
export type IconName = (typeof ICON_NAMES)[number];

/** Required semantic tokens, theme API 1.0 (spec §10.2.5). */
export const TOKEN_NAMES = ${list(tokens)};
export type TokenName = (typeof TOKEN_NAMES)[number];
`;
for (const [key, values] of Object.entries(layout)) {
  text += `\n/** Allowed values for \`${key}\`. */\nexport const ${constName(key)} = ${list(values)};\nexport type ${pascal(key)} = (typeof ${constName(key)})[number];\n`;
}

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== text) {
    console.error(`${out} is stale; run \`just gen\`.`);
    process.exit(1);
  }
  console.log("theme types (TS) are current");
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
