#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Build-time web plugin registry (M0S-E06-06).
//
//   node scripts/gen-plugin-registry.mjs           write apps/web/src/plugins/registry.gen.ts
//   node scripts/gen-plugin-registry.mjs --check   exit 1 if the file is stale
//
// Every manifest under plugins/official/* with `runtime.web` becomes a lazy import of its web package.
// Theme plugins never appear (they have no web code). Run by `just gen` and by Vite's buildStart.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = join(repo, "apps", "web", "src", "plugins", "registry.gen.ts");

export function collectManifests(root = join(repo, "plugins", "official")) {
  if (!existsSync(root)) return [];
  return readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(root, entry.name, "hearthos.plugin.json")))
    .map((entry) => JSON.parse(readFileSync(join(root, entry.name, "hearthos.plugin.json"), "utf8")));
}

export function renderRegistry(manifests) {
  const entries = manifests
    .filter((m) => typeof m?.runtime?.web === "string" && !(m.type ?? []).includes("theme"))
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((m) => `  ${JSON.stringify(m.id)}: () => import(${JSON.stringify(m.runtime.web)}),`);
  return `// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by scripts/gen-plugin-registry.mjs from the plugin manifests. Do not edit; run \`just gen\`.
import type { PluginWebModule } from "@hearthos/sdk-ts";

export const pluginRegistry: Record<string, () => Promise<{ default: PluginWebModule }>> = {
${entries.join("\n")}
};
`;
}

/** Write the registry if it changed; returns true when the file was (re)written. */
export function writeRegistry() {
  const text = renderRegistry(collectManifests());
  if (existsSync(OUT) && readFileSync(OUT, "utf8") === text) return false;
  writeFileSync(OUT, text);
  return true;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== renderRegistry(collectManifests())) {
      console.error("apps/web/src/plugins/registry.gen.ts is stale; run `just gen`");
      process.exit(1);
    }
  } else {
    writeRegistry();
  }
}
