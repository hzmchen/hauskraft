"""Generate Python types from the theme contract (M0S-E13-01).

python scripts/gen_theme_types.py           write packages/sdk-py/src/hearthos_sdk/theme_contract.py
python scripts/gen_theme_types.py --check   exit 1 if the file is stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
THEME = REPO / "packages" / "schemas" / "theme"
OUT = REPO / "packages" / "sdk-py" / "src" / "hearthos_sdk" / "theme_contract.py"


def _read(name: str) -> dict[str, object]:
    data: dict[str, object] = json.loads((THEME / name).read_text(encoding="utf-8"))
    return data


def _pascal(key: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in key.replace(".", "_").split("_"))


def _literal(name: str, values: list[str]) -> str:
    body = "".join(f"    {json.dumps(v)},\n" for v in values)
    return f"{name} = Literal[\n{body}]\n"


def _tuple(name: str, alias: str, values: list[str]) -> str:
    body = "".join(f"    {json.dumps(v)},\n" for v in values)
    return f"{name}: tuple[{alias}, ...] = (\n{body})\n"


def render() -> str:
    icons = list(_read("icon-names-v1.json")["icons"])  # type: ignore[call-overload]
    tokens = list(_read("tokens-v1.json")["tokens"])  # type: ignore[call-overload]
    layout = {k: list(v) for k, v in _read("layout-options-v1.json").items() if not k.startswith("$")}  # type: ignore[call-overload]
    parts = [
        # REUSE-IgnoreStart
        "# SPDX-License-Identifier: MIT\n",
        # REUSE-IgnoreEnd
        "# GENERATED by scripts/gen_theme_types.py from packages/schemas/theme. Do not edit; run `just gen`.\n",
        '"""Theme contract v1 as Python types (spec §10.2.5, §10.2.6, §10.2.1)."""\n\n',
        "from typing import Literal\n\n",
        _literal("IconName", icons),
        _tuple("CORE_ICON_NAMES", "IconName", icons),
        "\n",
        _literal("TokenName", tokens),
        _tuple("TOKEN_NAMES", "TokenName", tokens),
    ]
    for key, values in layout.items():
        parts += ["\n", _literal(_pascal(key), values)]
    return "".join(parts)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; run `just gen`.", file=sys.stderr)
            return 1
        print("theme types (Python) are current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
